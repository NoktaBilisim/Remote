// P28f K5 (AC-393/P28a, S-P28f-12): NSPasteboard gerçek gidiş-dönüş. Geliştiricinin genel panosuna dokunulmaz: her test
// benzersiz adlı panoyu kullanır ve Close'da releaseGlobally ile bırakır.

func uniqueClip(t *testing.T) *macClip {
	t.Helper()
	c, err := start(true)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(c.Close)
	return c
}

// putRaw panoya başka bir uygulama gibi UTF-8 metin verisi ve (varsa) ek boş türler koyar (text boş olmamalı).
func putRaw(t *testing.T, c *macClip, text string, extra ...string) {
	t.Helper()
	err := c.do(func() error {
		c.pb.Send(selClear)
		dataCls, _ := objc.GetClass("NSData")
		b := []byte(text)
		data := objc.ID(dataCls).Send(objc.Sel("dataWithBytes:length:"), unsafe.Pointer(&b[0]), uint(len(b)))
		runtime.KeepAlive(b)
		tt, _ := objc.NSString(typeText)
		if !pobjc.Send[bool](c.pb, selSetData, data, tt) {
			return ErrFailed
		}
		for _, e := range extra {
			et, _ := objc.NSString(e)
			if !pobjc.Send[bool](c.pb, selSetData, objc.ID(dataCls).Send(selData), et) {
				return ErrFailed
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

// hasType panoda tür var mı.
func hasType(t *testing.T, c *macClip, typ string) bool {
	t.Helper()
	var ok bool
	if err := c.do(func() error {
		ns, _ := objc.NSString(typ)
		ok = pobjc.Send[bool](c.pb.Send(selTypes), selContains, ns)
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	return ok
}

func TestAC393P28fClipRoundTripPlainText(t *testing.T) {
	c := uniqueClip(t)
	if _, err := c.ReadText(); !errors.Is(err, ErrEmpty) {
		t.Fatalf("boş pano: %v", err)
	}
	for _, s := range []string{"merhaba", "ç ğ ı ö ş ü İ\r\nikinci satır 😀", strings.Repeat("é", MaxBytes/2)} {
		putRaw(t, c, s)
		got, err := c.ReadText()
		if err != nil || got != s {
			t.Fatalf("gidiş-dönüş %d bayt: %v (eşit=%v)", len(s), err, got == s)
		}
	}
}

func TestAC393P28fClipReadLimits(t *testing.T) {
	c := uniqueClip(t)
	putRaw(t, c, strings.Repeat("a", MaxBytes+1))
	if _, err := c.ReadText(); !errors.Is(err, ErrTooLarge) {
		t.Fatalf("64 KB üstü: %v", err)
	}
	putRaw(t, c, strings.Repeat("a", 3*MaxBytes))
	if _, err := c.ReadText(); !errors.Is(err, ErrTooLarge) {
		t.Fatalf("kaba sınır: %v", err)
	}
}

// S-P28f-12: Concealed / Transient / AutoGenerated işaretli pano okunmaz.
func TestSP28f12ClipSensitiveMarksNotRead(t *testing.T) {
	c := uniqueClip(t)
	for _, mark := range []string{typeConcealed, typeTransient, typeAutoGen} {
		putRaw(t, c, "parola123", mark)
		if s, err := c.ReadText(); !errors.Is(err, ErrSensitive) || s != "" {
			t.Fatalf("%s: %q %v", mark, s, err)
		}
	}
}

// Windows TestP28aClipWindowsWriteMarksSensitive eşi: yazılan metin geçmiş dışı işaretlidir, geri okunursa SENSITIVE;
// panoda yalnız metin ve işaret vardır.
func TestAC393P28fClipWriteMarksTransient(t *testing.T) {
	c := uniqueClip(t)
	if err := c.WriteText("teknisyen metni ç"); err != nil {
		t.Fatal(err)
	}
	if !hasType(t, c, typeText) || !hasType(t, c, typeTransient) {
		t.Fatal("metin ya da TransientType yok")
	}
	if _, err := c.ReadText(); !errors.Is(err, ErrSensitive) {
		t.Fatalf("geri okuma: %v", err)
	}
	var got string
	if err := c.do(func() error {
		tt, _ := objc.NSString(typeText)
		var err error
		got, err = objc.GoString(c.pb.Send(objc.Sel("stringForType:"), tt))
		return err
	}); err != nil || got != "teknisyen metni ç" {
		t.Fatalf("yazılan metin: %q %v", got, err)
	}
}

func TestAC393P28fClipWriteValidation(t *testing.T) {
	c := uniqueClip(t)
	for name, s := range map[string]string{"boş": "", "NUL": "a\x00b", "geçersiz UTF-8": "a\xffb"} {
		if err := c.WriteText(s); !errors.Is(err, ErrInvalid) {
			t.Errorf("%s: %v", name, err)
		}
	}
	if err := c.WriteText(strings.Repeat("a", MaxBytes+1)); !errors.Is(err, ErrTooLarge) {
		t.Errorf("büyük: %v", err)
	}
}

