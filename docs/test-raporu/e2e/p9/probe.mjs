import { chromium, B, WORK, IMG, csrfFetch } from "./common.mjs";
const br = await chromium.launch();
const a = await (await br.newContext({ storageState: `${WORK}/state-admin.json` })).newPage();
await a.goto(B + "/users?status=passive"); await a.waitForLoadState("networkidle");
console.log("passive URL:", a.url(), "| main:", (await a.locator("main").innerText()).replace(/\n/g, " ").slice(0, 300));
const l = await csrfFetch(a, "GET", "/api/v1/users?status=passive"); console.log("API passive", l.status, l.body?.items?.length);
const sa = await (await br.newContext({ storageState: `${WORK}/state-sa.json` })).newPage();
await sa.goto(B + "/admin/tenants");
const t = await csrfFetch(sa, "GET", "/api/v1/admin/tenants?pageSize=100");
const other = t.body.items.find((x) => x.slug !== "demo");
await csrfFetch(sa, "POST", "/api/v1/admin/switch-tenant", { tenantId: other.id });
const u = await csrfFetch(sa, "GET", "/api/v1/users"); const oid = u.body.items[0].id;
await a.goto(B + `/users/${oid}`); await a.waitForLoadState("networkidle");
await a.screenshot({ path: IMG + "cross-tenant-user.png" });
console.log("cross:", (await a.locator("main").innerText()).replace(/\n/g, " ").slice(0, 200), "| testids:", await a.locator("[data-testid]").evaluateAll((e) => e.map((x) => x.dataset.testid).slice(0, 15).join(",")));
await sa.getByRole("button", { name: "Bu firmaya geç: Demo Firma" }).click();
await sa.waitForTimeout(1500);
console.log("acting after row:", await sa.getByTestId("tenant-switcher").getAttribute("data-acting"));
await sa.goto(B + "/users"); await sa.waitForLoadState("networkidle");
console.log("sa users:", (await sa.locator("main").innerText()).replace(/\n/g, " ").slice(0, 300));
await sa.screenshot({ path: IMG + "sa-after-row-switch.png" });
const m = await (await br.newContext({ storageState: `${WORK}/state-sa.json`, viewport: { width: 375, height: 800 }, isMobile: true })).newPage();
await m.goto(B + "/admin/tenants"); await m.waitForLoadState("networkidle"); await m.screenshot({ path: IMG + "tenants-375-probe.png" });
console.log(await m.evaluate(() => [...document.querySelectorAll("body *")].filter((e) => e.getBoundingClientRect().right > 376).slice(0,6).map((e) => e.tagName + "|" + e.className.toString().slice(0,90) + "|" + (e.textContent||"").slice(0,40) + "|" + e.closest("header,main")?.tagName).join("\n")));
const f = a; await f.goto(B + "/users"); await f.getByTestId("user-new").click();
console.log("maxlength name:", await f.getByTestId("user-form").getByLabel("Ad soyad").getAttribute("maxlength"));
await br.close();
